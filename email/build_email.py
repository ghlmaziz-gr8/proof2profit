# Builds supabase/invite_email.sql from email/invite.html. Run: python3 email/build_email.py
import pathlib
root = pathlib.Path(__file__).resolve().parent
tpl = (root / "invite.html").read_text().replace("\n", "")
assert "$T$" not in tpl and "'" not in tpl.replace("'Trebuchet MS'", "") , "unexpected quote in template"
tpl_sql = tpl.replace("'", "''")
sql = f"""-- Rich invitation email. Generated by email/build_email.py from email/invite.html.
create or replace function public.p2p_esc(t text) returns text language sql immutable as $$
  select replace(replace(replace(replace(coalesce(t, ''), '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;')
$$;

create or replace function public.invite_email_html(p_to text, p_role text, p_inviter text, p_note text, p_title text) returns text
language plpgsql immutable set search_path = public as $fn$
declare
  t text := '{tpl_sql}';
  who text := coalesce(nullif(trim(p_inviter), ''), 'The Proof to Profit team');
  role_label text; head text; intro text; blurb text; step2 text; step3 text; notes text := '';
begin
  role_label := case p_role when 'super' then 'SUPER USER' when 'admin' then 'ADMIN' when 'sales' then 'SALES' when 'member' then 'TEAM MEMBER' else 'BUSINESS OWNER' end;
  head := case p_role
    when 'member' then 'Join the team on Proof to Profit'
    when 'owner' then 'See what your customers really think'
    else 'Welcome to Proof to Profit' end;
  intro := public.p2p_esc(who) || ' has invited you to Proof to Profit, the AI that reads a business&rsquo;s reviews and turns them into scores, fixes and a plan for growing revenue.';
  blurb := case p_role
    when 'super' then 'You have full control of the platform: invitations, roles and everything else.'
    when 'admin' then 'You can invite and manage sales people and business owners, and see every invitation.'
    when 'sales' then 'You can invite business owners to Proof to Profit and see who has joined.'
    when 'member' then 'You are joining ' || public.p2p_esc(who) || '&rsquo;s team' || case when coalesce(trim(p_title), '') <> '' then ' as ' || public.p2p_esc(p_title) else '' end || '. Analyze businesses, save reports and track what changes over time.'
    else 'Analyze any business, save reports, track changes over time, and add your own managers and marketing crew to your team.' end;
  if p_role in ('super', 'admin', 'sales') then
    step2 := '<b>Click your name</b> at the top left, then <b>Invitations</b>.';
    step3 := '<b>Invite people</b> and watch them join. They get this same welcome.';
  else
    step2 := '<b>Paste a Google Maps link</b> or just a business name and city.';
    step3 := '<b>See the plan:</b> scores by topic, what guests love and what to fix first.';
  end if;
  if coalesce(trim(p_note), '') <> '' then
    notes := '<tr><td style="padding:16px 32px 0;font-family:Arial,Helvetica,sans-serif;"><table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr><td style="background:#ffffff;border:1px solid #E6DFD3;border-radius:14px;padding:14px 16px;font-size:14px;line-height:1.55;color:#5E5A54;"><b style="color:#14161A;">A note from ' || public.p2p_esc(who) || ':</b><br>&ldquo;' || public.p2p_esc(p_note) || '&rdquo;</td></tr></table></td></tr>';
  end if;
  t := replace(t, '{{PRE}}', public.p2p_esc(who) || ' invited you. Sign in with Google to get started.');
  t := replace(t, '{{HEAD}}', head);
  t := replace(t, '{{INTRO}}', intro);
  t := replace(t, '{{ROLE}}', role_label);
  t := replace(t, '{{BLURB}}', blurb);
  t := replace(t, '{{NOTEROW}}', notes);
  t := replace(t, '{{STEP2}}', step2);
  t := replace(t, '{{STEP3}}', step3);
  t := replace(t, '{{TO}}', public.p2p_esc(p_to));
  return t;
end $fn$;

create or replace function public.trg_allowed_email() returns trigger
language plpgsql security definer set search_path = public as $$
declare who text;
begin
  select coalesce(nullif(trim(p.display_name), ''), split_part(new.invited_by, '@', 1)) into who
  from auth.users u left join public.profiles p on p.user_id = u.id where lower(u.email) = lower(new.invited_by) limit 1;
  who := coalesce(who, nullif(split_part(coalesce(new.invited_by, ''), '@', 1), ''));
  perform public.queue_email(null, new.email, 'welcome',
    case when who is null then 'You are invited to Proof to Profit' else who || ' invited you to Proof to Profit' end,
    public.invite_email_html(new.email, new.role, who, new.note, new.title));
  return new;
end $$;
"""
(root.parent / "supabase" / "invite_email.sql").write_text(sql)
print(len(sql), "bytes")
